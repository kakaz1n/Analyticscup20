"""Write docs/RESULTS.md from the built data (reproducible: `python -m dbl report`)."""
from __future__ import annotations

from datetime import date

from .config import MATCHES, ROOT
from .data.load import load_meta
from .goals import find_goals, goal_breakdown
from .shape import event_kpis, insights
from .simulate import simulate_goal
from .store import MomentStore


def _pct(x):
    return "–" if x is None or x != x else f"{x:.0%}"


def build_results(path=None) -> str:
    s = MomentStore()
    L = ["# Results", "",
         f"_Generated by `python -m dbl report` on {date.today().isoformat()} from the built data. "
         "Two matches only: read every number as an association to prioritise video review, not as a causal effect._", ""]

    # ---------------------------------------------------------------- sample
    L += ["## 1. Sample", "",
          "| Moment family | Rows | With body pose |", "|---|---|---|"]
    cov = {"duels": "body_shape", "passes": "vision", "runs": "blind_side", "recoveries": "turned_within_1s"}
    for t, df in s.tables.items():
        L.append(f"| {t} | {len(df):,} | {_pct(df[cov[t]].notna().mean())} |")
    L.append("")

    # ---------------------------------------------------------------- evidence
    ev = s.all_evidence()
    L += ["## 2. Do the coaching cues show up in the outcomes?", "",
          "Stratified risk difference (exposed − other), 95 % percentile bootstrap CI over moments (1,000 resamples).", "",
          "| Principle | Cue | Exposure → outcome | Exposed | Other | Adjusted diff [95 % CI] | Strata |",
          "|---|---|---|---|---|---|---|"]
    for r in ev.itertuples():
        lo, hi = r.adj_diff_ci
        L.append(f"| {r.principle} | {r.cue} | {r.exposure_label} → {r.outcome} | {r.rate_exposed:.1%} (n={r.n_exposed}) | "
                 f"{r.rate_other:.1%} (n={r.n_other}) | **{r.adj_diff:+.1%}** [{lo:+.1%}, {hi:+.1%}] | {', '.join(r.strata)} |")
    L += ["", "![Figure 1](fig1_evidence.png)", ""]

    # ---------------------------------------------------------------- teams
    L += ["## 3. Team defensive profiles", ""]
    tp = s.team_profile()
    cols = ["team", "side_on", "loaded", "regain", "dual_vision", "checks_per_pass", "receiver_free",
            "blind_side_runs", "square_at_run", "beaten_in_behind", "reaction_lag_s"]
    L += ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in tp[cols].itertuples(index=False):
        L.append("| " + " | ".join(f"{v:.2f}" if isinstance(v, float) else str(v) for v in r) + " |")
    L.append("")
    for m in MATCHES:
        meta = load_meta(m)
        ins = insights(m, s)
        L += [f"### {meta.title}", ""]
        for team, bullets in ins["bullets"].items():
            L.append(f"**{team} — defending**")
            L += [f"- {b}" for b in bullets]
            L.append("")
        k = event_kpis(m)
        L += ["| Team | PPDA* | Counter-presses | Pressing chains → regain | Regains | Line breaks conceded | Last-line breaks | Shots conceded |",
              "|---|---|---|---|---|---|---|---|"]
        for r in k.itertuples():
            L.append(f"| {r.team} | {r.ppda} | {r.counter_presses} | {r.chain_regains} | {r.regains} | "
                     f"{r.line_breaks_conceded} / {r.opp_passes} | {r.last_line_breaks_conceded} | {r.opp_shots} |")
        L += ["", "_*PPDA from SkillCorner engagements ending in regain/disruption/foul — not comparable with event-provider PPDA._", ""]

    # ---------------------------------------------------------------- goals
    L += ["## 4. Goals: how they happened, responsibility, and how they could have been prevented", ""]
    for m in MATCHES:
        meta = load_meta(m)
        L += [f"### {meta.title}", ""]
        for g in find_goals(m):
            b = goal_breakdown(m, g["goal_number"], s)
            sim = simulate_goal(m, g["goal_number"])
            seq = " → ".join(f"{x['player']}" + (" (shot)" if x["action"] == "shot" else "") for x in b["sequence"][-6:])
            L.append(f"**Goal {g['goal_number']} — {g['time']} {g['scorer']} ({g['team']})**"
                     + (f", assist {g['assist']}" if g.get("assist") else "") + f" · {g['score_after']}")
            L.append(f"- Build-up: {seq}")
            a = b.get("at_shot") or {}
            if a.get("defender"):
                L.append(f"- At the shot: nearest defender {a['defender']} at {a['distance_m']} m "
                         f"({'goal-side' if a['goal_side'] else 'not goal-side'}), {a['defenders_in_shot_line']} in the shot line, "
                         f"shot from {a['shot_distance_m']} m")
            top = b["responsibility"][:3]
            if top:
                L.append("- Responsibility indicators: " + "; ".join(
                    f"**{r['defender']}** {r['points']} pts ({', '.join(x.split(': ', 1)[-1].rsplit(' (+', 1)[0] for x in r['reasons'][:2])})"
                    for r in top))
            if "before" in sim:
                k = sim.get("key_fix")
                L.append(f"- Simulation at the {sim['moment']}: danger **−{sim['danger_reduction']:.0%}**, free attackers "
                         f"{sim['before']['free_attackers']} → {sim['after']['free_attackers']}"
                         + (f", nearest defender to the scorer {sim['before'].get('focus_marker_dist')} → {sim['after'].get('focus_marker_dist')} m"
                            if sim['before'].get('focus_marker_dist') is not None else "")
                         + (f"; key fix: **{k['defender']}** — {k['why']} ({k['move_m']} m)" if k else ""))
            L.append("")
    L += ["Reading the simulation: a large reduction means the goal was preventable by positioning within the "
          "reaction window; a small one (< 10 %) means the defence was already near its best reachable shape and the "
          "goal came from elsewhere (finishing, an individual action, a set-piece second ball).", ""]
    text = "\n".join(L)
    path = path or ROOT / "docs" / "RESULTS.md"
    path.write_text(text, encoding="utf-8")
    return str(path)


if __name__ == "__main__":
    print(build_results())
